$teacher$## Your role
Teachers bring the practice to Stretchy.

We want you to teach in your own voice and bring your own experience, personality and expertise. Stretchy isn't about making every class the same.

## Before class
- Arrive prepared and ready to teach.
- Communicate early if you're sick, injured or unable to teach.
- Work with the GEM to make sure the room is ready.
- Flag any venue, participant or operational issues to HQ.

## During class
- Create a welcoming and inclusive environment.
- Give clear instructions and appropriate options/modifications.
- Be mindful of different bodies, abilities and experience levels.
- Treat participants with warmth and respect.
- Let the GEM know if you need anything.

## After class
- Help the group naturally transition into Social Stretch.
- Flag anything important to HQ.
- Share feedback or ideas that could make the experience better.

## If something goes wrong
If there's an injury, complaint, venue issue or anything that doesn't feel right, don't sit on it.

Let the GEM and/or Kimberley know.

You don't need to solve everything yourself.$teacher$,

$gem$## GEM = Good Energy Manager
You're the friendly face of Stretchy on the ground.

You're there to help people arrive, settle in, connect and have a great time — from the first hello through to Social Stretch.

Think: **NOTICE. WELCOME. CONNECT.**

You're not there to run the yoga class. You're there to help make the whole Stretchy experience feel warm, easy and very Stretchy.

## Your session
Your standard rostered session is 2 paid hours.

**15 minutes before yoga**
- Open / prepare the space
- Get the Stretchy setup ready
- Get the speaker charged and connected
- Welcome people
- Check attendees in through the Stretchy app
- Help the teacher get set up

**1 hour yoga**
- You're welcome to participate in the Stretchy class
- Be aware of relevant injury/accessibility information available through the app
- Keep an eye on the room and community
- Help where needed

**45 minutes after yoga**
- Help pack down
- Help people transition into Social Stretch
- Make sure the group knows where they're heading
- Help solo attendees and new people connect
- Flag anything important to HQ

Anything beyond your contracted 2 hours is your own personal time.

## The GEM mindset
You don't need to force people to socialise. Instead: notice who might need a hello. Welcome people in. Connect people naturally.

A simple **“Hey, have you been to Stretchy before?”** can be enough to start a conversation.

## Your regular location
Where possible, you'll be the regular GEM for your assigned location.

The idea is that seeing the same friendly face each week/month creates familiarity, trust and continuity for the community.

Once you've accepted a rostered session, we rely on you to be there. If something comes up, give Kimberley as much notice as possible so we can find cover. For illness or emergencies, let her know ASAP.

## Stretchy 2.0 & session cancellations
Stretchy 2.0 checks minimum attendance 36 hours before the session.

If the minimum isn't reached and the session is cancelled, your agreed pay for that rostered session is still honoured.

The specific mechanics and platform information are confidential and are covered by your NDA.

## Content
We love capturing little moments of Stretchy life.

GEMs can take a few discrete, organic photos or short video clips where appropriate. Think:
- Wide shots of the group
- Interesting angles and little moments
- Setup, arrivals, mats in the room
- Coffee / drinks
- Moments of connection

Where possible, capture content so people aren't super recognisable.

If you're capturing anything at the Social Stretch, please ask people first before taking photos or video.

You are not expected to be a professional content creator. And never pressure anyone to be in content.

