$everyone$Whether you’re part of Stretchy HQ, a Teacher, Good Energy Manager (GEM), venue or partner, you’re part of creating the Stretchy experience.

This is the quick version of what matters. Your individual agreement, role description and onboarding information contain the more specific details.

## What is Stretchy?
Stretchy is a social movement built around movement.

We bring people together through yoga, movement and what happens afterwards: coffee, drinks, chats and new connections.

We stretch bodies, minds and social circles.

You can come alone, come with mates, or come hoping to make some new ones.

At the heart of Stretchy is a simple idea: **The more people who come together, the better it gets for all.**

## The Stretchy feeling
We want Stretchy to feel welcoming, easy, social and a little bit fun.

For some people, walking into a room full of strangers can be a big deal. We don't take that for granted.

Whether someone is brand new to yoga, coming alone, returning after a break or simply having a hard week, we want them to feel like they belong here.

We welcome people in. We don't make them earn their place.

## How we show up
- **EMBRACE ALL** Create space for people as they are. Be inclusive, respectful and mindful that everyone arrives with different experiences, bodies, abilities and comfort levels.
- **GIVE GOOD ENERGY** Bring warmth, enthusiasm and generosity to what you do. You don't need to be the loudest person in the room to make someone feel welcome.
- **PEOPLE FIRST** Stretchy is a business, but it's also a community. We care about doing things sustainably and fairly while protecting the experience of the people who show up.
- **MAKE IT BETTER** Stretchy 2.0 is being built and tested as we go. Stay curious, listen to feedback and speak up when something could work better.
- **KEEP IT KIND** No discrimination, harassment, bullying, inappropriate behaviour or unwanted advances. We all have a role in keeping Stretchy safe and respectful.
- **BE RELIABLE** People are trusting us with their time, money and experience. Turn up when you say you will, communicate early if something changes and follow through on what you've agreed to.

## Stretchy 2.0
Stretchy is doing things a little differently.

Our people-powered social pricing means the number of people who join a session can improve the price for everyone.

The platform checks whether the minimum attendance has been reached 36 hours before a session. If it has, the Stretchy is confirmed.

The final price is then locked 2 hours before the session, when attendees are charged.

Until then, more people joining can make the price better for everyone.

If someone asks, keep it simple: **“The more people who come together, the better it can get for everyone.”**

You don't need to explain the technical mechanics unless it's part of your role.

## Community first
People may arrive alone. They may be nervous. They may be new to yoga. They may know absolutely nobody.

Notice that. Say hello. Introduce people. Make room.

And remember that Social Stretch is part of the experience, not an optional extra. The yoga gets people together; what happens afterwards is where a lot of the connection happens.

## Privacy, confidentiality & IP
Some parts of Stretchy 2.0 are intentionally private while we're building and testing them.

Please keep confidential any non-public information you have access to, including:
- attendee and community information
- injury or accessibility information
- platform and operational information
- internal systems and processes
- non-public Stretchy 2.0 mechanics
- brand, creative and intellectual property

Don't screenshot, export or share private attendee information, or put it into personal/public AI tools.

Stretchy's brand, systems, language, creative ideas and 2.0 mechanics are part of the IP we're building. Please don't copy, reproduce or use them outside your work with Stretchy without permission.

Your NDA and/or individual agreement covers the more specific requirements.

